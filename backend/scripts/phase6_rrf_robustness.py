"""
backend/scripts/phase6_rrf_robustness.py
=========================================
CineSuggest AI — Phase 6: RRF Robustness & Personalization Validation.

Requirements Addressed:
1. Multiple Random Seeds (5 seeds: 42, 101, 2024, 31415, 9999):
   - Evaluates Popularity, User CF, Item CF, SVD, Hybrid CF, and RRF.
   - Reports mean +- std across 5 independent train/test splits.
2. Statistical Comparison:
   - Paired per-user differences (RRF vs Hybrid CF, RRF vs Popularity).
   - 2,000 paired bootstrap iterations for 95% Confidence Intervals & p-values.
   - Statistically honest conclusions based strictly on CI bounds.
3. Personalization Measurement:
   - Mean pairwise Jaccard similarity across users' top-10 lists.
   - Number of unique items recommended & catalog coverage.
   - Overlap with Popularity baseline (mean Jaccard vs Popularity).
   - Evaluated separately for Sparse (Given N=2) and Mature (Full 80% Train) users.
4. RRF Component Ablation:
   - Full 3-Way (UserCF + ItemCF + SVD)
   - 2-Way (UserCF + ItemCF)
   - 2-Way (UserCF + SVD)
   - 2-Way (ItemCF + SVD)
   - Shows marginal contribution of each model under fixed k_rrf = 60.
5. Rank-List Integrity Verification:
   - Deterministic tie-breaking (RRF score desc, popularity desc, movieId asc).
   - Zero contribution for unranked candidates.
   - Check count of users receiving < 10 recommendations.
"""

import os
import sys
import math
import numpy as np
import pandas as pd

ML_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ml")
K = 10
K_RRF = 60
REL_THRESH = 4.0
MIN_CANDIDATE_COUNT = 10
SEEDS = [42, 101, 2024, 31415, 9999]

movies_csv = os.path.join(ML_DIR, "movies.csv")
ratings_csv = os.path.join(ML_DIR, "ratings.csv")
if not os.path.exists(ratings_csv):
    ratings_csv = os.path.join(ML_DIR, "ratings.csv.csv")

df_movies = pd.read_csv(movies_csv)
df_ratings = pd.read_csv(ratings_csv)

all_user_ids = np.sort(df_ratings["userId"].unique())
all_movie_ids = np.sort(df_ratings["movieId"].unique())
u2i = {uid: i for i, uid in enumerate(all_user_ids)}
m2j = {mid: j for j, mid in enumerate(all_movie_ids)}
n_users = len(all_user_ids)
n_items = len(all_movie_ids)


def fit_and_evaluate_split(seed, is_ablation=False, sparse_eval=False):
    """
    Fits training models strictly on an 80/20 split generated by `seed` and evaluates models.
    """
    rng = np.random.default_rng(seed)
    train_indices_list = []
    test_indices_list = []

    for uid, group in df_ratings.groupby("userId"):
        idx = group.index.values.copy()
        rng.shuffle(idx)
        n_hold = max(1, int(round(len(idx) * 0.20)))
        test_indices_list.append(idx[:n_hold])
        train_indices_list.append(idx[n_hold:])

    all_train_idx = np.concatenate(train_indices_list)
    all_test_idx = np.concatenate(test_indices_list)
    df_train = df_ratings.loc[all_train_idx].reset_index(drop=True)
    df_test = df_ratings.loc[all_test_idx].reset_index(drop=True)

    # Global Mean
    global_mean_train = float(df_train["rating"].mean())

    # Build R_train
    R_train = np.full((n_users, n_items), np.nan, dtype=np.float32)
    for _, row in df_train.iterrows():
        R_train[u2i[int(row["userId"])], m2j[int(row["movieId"])]] = float(row["rating"])

    mask_train = ~np.isnan(R_train)
    train_counts = mask_train.sum(axis=0)

    # Candidate catalog
    eligible_catalog_mask = (train_counts >= MIN_CANDIDATE_COUNT)
    eligible_catalog_indices = np.where(eligible_catalog_mask)[0]
    n_eligible_catalog = len(eligible_catalog_indices)

    # User means
    user_means_train = np.full(n_users, global_mean_train, dtype=np.float32)
    for ui in range(n_users):
        vals = R_train[ui, mask_train[ui]]
        if len(vals) > 0:
            user_means_train[ui] = float(np.mean(vals))

    Rc_train = np.where(mask_train, R_train - user_means_train[:, None], 0.0).astype(np.float32)
    user_norm_train = np.linalg.norm(Rc_train, axis=1)
    item_norm_train = np.linalg.norm(Rc_train, axis=0)

    # Item similarity
    denom_item = item_norm_train[:, None] * item_norm_train[None, :] + 1e-9
    item_sim_mat = (Rc_train.T @ Rc_train) / denom_item
    np.fill_diagonal(item_sim_mat, 0.0)
    pos_item_sim_mat = np.maximum(0.0, item_sim_mat)

    # SVD
    U_svd, S_svd, Vt_svd = np.linalg.svd(Rc_train, full_matrices=False)
    K_SVD = 20
    P_train = U_svd[:, :K_SVD] * S_svd[:K_SVD]
    Q_train = Vt_svd[:K_SVD, :].T

    # Item biases
    item_biases_train = np.zeros(n_items, dtype=np.float32)
    for j in range(n_items):
        u_idx = np.where(mask_train[:, j])[0]
        if len(u_idx) > 0:
            item_biases_train[j] = float(np.mean(R_train[u_idx, j] - user_means_train[u_idx]))

    # Popularity ordering
    pop_ranked_candidates = [j for j in np.argsort(-train_counts) if eligible_catalog_mask[j]]

    # Pre-compute test items by user
    test_by_user = {}
    for _, row in df_test.iterrows():
        test_by_user.setdefault(int(row["userId"]), []).append((int(row["movieId"]), float(row["rating"])))

    # Models to evaluate
    if is_ablation:
        alg_names = ["RRF (3-Way)", "RRF (User+Item)", "RRF (User+SVD)", "RRF (Item+SVD)", "User-Based CF", "Item-Based CF", "SVD"]
    else:
        alg_names = ["Popularity", "User-Based CF", "Item-Based CF", "SVD", "Hybrid CF", "RRF"]

    per_user_metrics = {alg: {} for alg in alg_names}
    user_rec_lists = {alg: {} for alg in alg_names}
    users_with_lt10 = {alg: 0 for alg in alg_names}

    # Evaluate all 610 users
    eval_uids = all_user_ids

    for uid in eval_uids:
        ui = u2i[uid]
        full_train_j = np.where(mask_train[ui])[0]

        if sparse_eval:
            # Simulate Given N=2 cold-start profile
            if len(full_train_j) <= 2:
                train_j = full_train_j
            else:
                shuf = rng.permutation(full_train_j)
                train_j = shuf[:2]
        else:
            train_j = full_train_j

        if len(train_j) == 0:
            continue

        train_ratings = R_train[ui, train_j]
        u_mean = float(np.mean(train_ratings))
        train_rc = np.zeros(n_items, dtype=np.float32)
        train_rc[train_j] = train_ratings - u_mean

        test_items = test_by_user.get(uid, [])

        # 1. User CF
        nrm = float(np.linalg.norm(train_rc))
        if nrm > 0:
            u_sims = (Rc_train @ train_rc) / (user_norm_train * nrm + 1e-9)
            u_sims[ui] = 0.0
            pos_u = np.maximum(0.0, u_sims)
            top_u = np.argsort(-pos_u)[:30]
            top_u = top_u[pos_u[top_u] > 0]
            if len(top_u) > 0:
                w_s = pos_u[top_u]
                m_s = mask_train[top_u].astype(np.float32)
                sup = m_s.sum(axis=0)
                num = w_s @ Rc_train[top_u]
                den = w_s @ m_s
                shrink = sup / (sup + 2.0)
                with np.errstate(divide="ignore", invalid="ignore"):
                    p_ub = u_mean + shrink * (num / (den + 1e-9))
                p_ub[(den <= 0) | (sup < 3)] = np.nan
            else:
                p_ub = np.full(n_items, np.nan)
        else:
            p_ub = np.full(n_items, np.nan)

        # 2. Item CF
        sim_sub = pos_item_sim_mat[train_j, :]
        sim_sum = sim_sub.sum(axis=0)
        dev_r = train_rc[train_j]
        weighted_dev = sim_sub.T @ dev_r
        p_ib = np.where(sim_sum > 0, u_mean + weighted_dev / (sim_sum + 0.5), np.nan)

        # 3. SVD
        if len(train_j) > 0:
            Q_r = Q_train[train_j]
            rc_r = train_rc[train_j]
            reg = 2.0 * np.eye(K_SVD)
            p_u = np.linalg.solve(Q_r.T @ Q_r + reg, Q_r.T @ rc_r)
            p_svd = u_mean + item_biases_train + (p_u @ Q_train.T)
        else:
            p_svd = np.full(n_items, u_mean)

        # 4. Hybrid CF
        n_r = len(train_j)
        weights = (0.20, 0.60, 0.20) if n_r <= 3 else (0.30, 0.40, 0.30)
        min_sim = 0.25 if n_r <= 3 else 0.15
        profile_counts = train_counts[train_j]
        has_anchor = bool((profile_counts >= 10).any() or (profile_counts.sum() >= 15))
        has_user_cf = bool((~np.isnan(p_ub)).any())

        if not has_anchor and not has_user_cf:
            p_hybrid = np.full(n_items, np.nan)
        else:
            has_collab = (~np.isnan(p_ub)) | (sim_sum >= min_sim)
            preds_m = np.column_stack([p_ub, p_ib, p_svd])
            w_v = np.asarray(weights, dtype=float)[None, :] * ~np.isnan(preds_m)
            tw = w_v.sum(axis=1)
            p_hybrid = np.where(has_collab & (tw > 0), (np.nan_to_num(preds_m) * w_v).sum(axis=1) / tw, np.nan)

        # Candidate pool
        base_eligible = eligible_catalog_mask.copy()
        base_eligible[train_j] = False

        def rank_cands(score_arr, top_n=50):
            cand_mask = base_eligible & (~np.isnan(score_arr)) & np.isfinite(score_arr)
            cand_j = np.where(cand_mask)[0]
            if len(cand_j) == 0:
                return []
            cand_scores = score_arr[cand_j]
            top_local = np.argsort(-cand_scores)[:top_n]
            return cand_j[top_local].tolist()

        list_pop = [j for j in pop_ranked_candidates if base_eligible[j]][:K]
        list_ub = rank_cands(p_ub, top_n=50)
        list_ib = rank_cands(p_ib, top_n=50)
        list_svd = rank_cands(p_svd, top_n=50)
        list_hyb = rank_cands(p_hybrid, top_n=K)

        def fuse_rrf(list_tuple):
            scores = {}
            for r_list in list_tuple:
                for rank_idx, j in enumerate(r_list, 1):
                    scores[j] = scores.get(j, 0.0) + (1.0 / (K_RRF + rank_idx))
            if not scores:
                return []
            # Deterministic tie-breaking: score desc, train_counts desc, index asc
            sorted_items = sorted(scores.items(), key=lambda x: (x[1], train_counts[x[0]], -x[0]), reverse=True)
            return [j for j, _ in sorted_items[:K]]

        if is_ablation:
            lists_dict = {
                "RRF (3-Way)": fuse_rrf((list_ub, list_ib, list_svd)),
                "RRF (User+Item)": fuse_rrf((list_ub, list_ib)),
                "RRF (User+SVD)": fuse_rrf((list_ub, list_svd)),
                "RRF (Item+SVD)": fuse_rrf((list_ib, list_svd)),
                "User-Based CF": list_ub[:K],
                "Item-Based CF": list_ib[:K],
                "SVD": list_svd[:K],
            }
        else:
            lists_dict = {
                "Popularity": list_pop,
                "User-Based CF": list_ub[:K],
                "Item-Based CF": list_ib[:K],
                "SVD": list_svd[:K],
                "Hybrid CF": list_hyb,
                "RRF": fuse_rrf((list_ub, list_ib, list_svd)),
            }

        # Store recommendations
        for alg, recs in lists_dict.items():
            user_rec_lists[alg][uid] = recs
            if len(recs) < K:
                users_with_lt10[alg] += 1

        # Relevant test items
        rel_test_j = set(m2j[mid] for mid, r_true in test_items if mid in m2j and r_true >= REL_THRESH)
        if len(rel_test_j) > 0:
            idcg = sum(1.0 / math.log2(rk + 2) for rk in range(min(len(rel_test_j), K)))
            for alg, recs in lists_dict.items():
                hits = len(rel_test_j.intersection(recs))
                prec = hits / K
                rec = hits / len(rel_test_j)
                dcg = sum(1.0 / math.log2(rk + 2) for rk, j in enumerate(recs) if j in rel_test_j)
                ndcg = dcg / idcg if idcg > 0 else 0.0
                per_user_metrics[alg][uid] = {"prec": prec, "rec": rec, "ndcg": ndcg}

    return {
        "per_user_metrics": per_user_metrics,
        "user_rec_lists": user_rec_lists,
        "n_eligible_catalog": n_eligible_catalog,
        "users_with_lt10": users_with_lt10,
        "train_counts": train_counts,
    }


def compute_personalization_metrics(user_rec_lists, n_eligible_catalog, pop_recs_dict):
    """
    Computes:
    - Mean pairwise Jaccard similarity across users' top-10 lists.
    - Unique items recommended across all users.
    - Catalog coverage (% of eligible catalog).
    - Mean Jaccard overlap with Popularity baseline.
    """
    uids = list(user_rec_lists.keys())
    n_u = len(uids)

    # 1. Unique items & Catalog coverage
    all_rec_items = set()
    for u in uids:
        all_rec_items.update(user_rec_lists[u])
    unique_items_count = len(all_rec_items)
    cat_cov_pct = (unique_items_count / n_eligible_catalog) * 100.0

    # 2. Overlap with Popularity
    pop_overlaps = []
    for u in uids:
        u_set = set(user_rec_lists[u])
        p_set = set(pop_recs_dict.get(u, []))
        if len(u_set) > 0 or len(p_set) > 0:
            jacc = len(u_set.intersection(p_set)) / len(u_set.union(p_set))
            pop_overlaps.append(jacc)
    mean_pop_overlap = float(np.mean(pop_overlaps)) if pop_overlaps else 0.0

    # 3. Pairwise Jaccard similarity (sample up to 200 users for quick deterministic computation)
    eval_sample_uids = uids[:200]
    m_sample = len(eval_sample_uids)
    sets = [set(user_rec_lists[u]) for u in eval_sample_uids]
    pairwise_jaccards = []
    for i in range(m_sample):
        s_i = sets[i]
        for k in range(i + 1, m_sample):
            s_k = sets[k]
            un = s_i.union(s_k)
            if len(un) > 0:
                pairwise_jaccards.append(len(s_i.intersection(s_k)) / len(un))
            else:
                pairwise_jaccards.append(0.0)
    mean_pairwise_jaccard = float(np.mean(pairwise_jaccards)) if pairwise_jaccards else 0.0

    return {
        "pairwise_jaccard": mean_pairwise_jaccard,
        "unique_items": unique_items_count,
        "cat_cov_pct": cat_cov_pct,
        "pop_overlap": mean_pop_overlap,
    }


def paired_bootstrap_ci(uids, metrics_A, metrics_B, metric_key="prec", n_boot=2000, seed=42):
    """
    Paired bootstrap for difference Metric(A) - Metric(B) across matched users.
    Returns: mean_diff, ci_lower, ci_upper, p_value.
    """
    rng = np.random.default_rng(seed)
    diffs = np.array([metrics_A[u][metric_key] - metrics_B[u][metric_key] for u in uids])
    n = len(diffs)
    boot_means = np.empty(n_boot, dtype=np.float64)

    for b in range(n_boot):
        sample_idx = rng.integers(0, n, size=n)
        boot_means[b] = np.mean(diffs[sample_idx])

    mean_diff = float(np.mean(diffs))
    ci_lower = float(np.percentile(boot_means, 2.5))
    ci_upper = float(np.percentile(boot_means, 97.5))

    # Two-sided empirical p-value
    p_val = 2.0 * min(np.mean(boot_means <= 0), np.mean(boot_means >= 0))
    p_val = min(1.0, p_val)

    return mean_diff, ci_lower, ci_upper, p_val


